function rotateChoices(values, offset) {
  if (!values.length) return []
  const shift = offset % values.length
  return [...values.slice(shift), ...values.slice(0, shift)]
}

function distinctCoreDistractors(item, index) {
  const sameCategory = kotenCultureByCategory(item.category)
  const ordered = [
    ...sameCategory.slice(index + 1),
    ...sameCategory.slice(0, index),
    ...KOTEN_CULTURE,
  ]
  const values = []
  for (const candidate of ordered) {
    if (!candidate.core || candidate.core === item.core || values.includes(candidate.core)) continue
    values.push(candidate.core)
    if (values.length === 3) break
  }
  return values
}

