export function syntaxFamilyIdFor(item) {
  if (!item || item.kind !== 'syntax') return null
  return SYNTAX_ITEM_FAMILY_OVERRIDES[item.id]
    || (item.sourceTopic && SYNTAX_TOPIC_FAMILY[item.sourceTopic])
    || MANUAL_SYNTAX_FAMILY[item.id]
    || null
}

export function syntaxFamilyFor(item) {
  const id = syntaxFamilyIdFor(item)
  return id ? SYNTAX_FAMILY_BY_ID[id] ?? null : null
}

export function syntaxFamilySearchText(item) {
  const guide = syntaxFamilyFor(item)
  if (!guide) return ''
  return [
    guide.title,
    guide.summary,
    guide.decision,
    guide.examTip,
    ...guide.patterns.flatMap((pattern) => [
      pattern.form,
      pattern.meaning,
      pattern.example,
      pattern.ja,
    ]),
    ...guide.pitfalls,
  ].filter(Boolean).join(' ')
}
