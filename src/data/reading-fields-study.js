const expression = (id, level, phrase, meaning, en, ja, note, kind = 'idiom') =>
  Object.freeze({
    id: 'rdf_' + id,
    kind,
    category: 'expression',
    level,
    phrase,
    meaning,
    meanings: [meaning],
    example: Object.freeze({ en, ja }),
    origin: note,
    note,
  })

