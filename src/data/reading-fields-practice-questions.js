// 分野長文で、内容理解とは別に「語順・文法・語法」を本文の実文で練習する。
// 各長文へ3形式を1問ずつ置き、本文の長さによって特定形式が減らないようにする。

const freezeList = (items) => Object.freeze(items.map((item) => Object.freeze(item)))

const orderQuestion = ({
  id,
  sourceSentence,
  sourceJa,
  explain,
  readingRuleId,
  vocabIds,
}) => Object.freeze({
  id,
  questionType: 'word-order',
  q: 'Arrange the words to rebuild the sentence from the passage.',
  questionJa: '本文の意味になるように、単語を英文の順に並べなさい。',
  cueJa: sourceJa,
  choices: Object.freeze([]),
  answer: sourceSentence,
  answerJa: sourceJa,
  sourceSentence,
  sourceJa,
  explain,
  readingRuleId,
  vocabIds: Object.freeze(vocabIds),
})

const choiceQuestion = ({
  id,
  questionType,
  q,
  questionJa,
  cueJa,
  answer,
  sourceSentence,
  sourceJa,
  explain,
  readingRuleId,
  vocabIds,
  choices,
}) => {
  const choiceValues = choices.map(([choice]) => choice)
  return Object.freeze({
    id,
    questionType,
    q,
    questionJa,
    cueJa,
    choices: Object.freeze(choiceValues),
    answer,
    answerJa: sourceJa,
    sourceSentence,
    sourceJa,
    explain,
    readingRuleId,
    vocabIds: Object.freeze(vocabIds),
    choiceTranslations: Object.freeze(Object.fromEntries(
      choices.map(([choice, translation]) => [choice, translation]),
    )),
    choiceNotes: Object.freeze(Object.fromEntries(
      choices.map(([choice, , note]) => [choice, note]),
    )),
  })
}

