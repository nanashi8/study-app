// 語根オートリンクの検出器（精度重視・形態素分解＋除外リスト）。
const ROOT_MATCHERS = buildRootMatchers(ROOTS)

// 各単語に root id 配列を付与する。
//  1) 手書きの etymology.parts[].root（最優先・最も正確）
//  2) 形態素分解で確実に当たる語根（derive-roots）を追記
// （データ側で roots を二重管理しないため、ここで一元的に導出）
const normalize = (w) => {
  const manual = (w.etymology?.parts ?? []).map((p) => p.root).filter(Boolean)
  const auto = autoRootIds((w.word ?? '').toLowerCase(), ROOT_MATCHERS)
  const roots = [...new Set([...manual, ...auto])]
  // meaning を正本として、取り込み済みデータも括弧を考慮した分割へ統一する。
  const meaning = w.meaning ?? w.meanings?.join('・') ?? ''
  const meanings = splitMeanings(meaning)
  // 発音記号(IPA)は手書き値→品詞/語義別補正→CMU辞書の順で採用。
  const phonetic =
    w.phonetic ||
    PHONETIC_OVERRIDES[w.id] ||
    PHONETICS[w.word?.toLowerCase()] ||
    ''
  // 級(level)補正：基本語の過大級づけを英検の実級へ補正（levels-override.js）。
  const level = LEVEL_OVERRIDE[w.word?.toLowerCase()] || w.level
  // 補助情報（類義語/反対語/派生語/使い方）は各語のタプル8番目に内包済み。
  return {
    ...w,
    level,
    roots,
    meanings,
    meaning,
    phonetic,
    synonyms: w.synonyms ?? [],
    antonyms: w.antonyms ?? [],
    derivatives: w.derivatives ?? [],
    family: w.family ?? [],
    usage: w.usage ?? '',
    usageGuides: w.usageGuides ?? USAGE_GUIDES_BY_WORD[w.id] ?? [],
  }
}

