// 旧family索引の自動拡充（packId保存互換のため維持）。
// ここには語形・複合語・明記された由来の複数経路が混ざるため、学習者向け画面で
// 一律に「同じ語根・語族」とは表示せず、辞書画面にもこの自動一覧は出さない。
// 4経路のリンクを張り、各語の family を最大 FAM_MAX 件まで関連見出し語で補う。
//   (1) 手書き語源リンクの双方向化：語源が「base(意味)+ -suffix」等で基語を名指しし、その基語が
//       見出し語なら 派生語⇔基語 を相互リンク（例: knowledge⇔know, happiness⇔happy）。
//   (2) 語源説明が見出し語を「同源・同系・同根」と明記していれば、その組を双方向化。
//       既存の説明に根拠が明記された組だけを拾い、綴りの似た別語を推測でつながない。
//   (3) 超安全な接尾辞のみ(-ness/-less/-ful/-ship/-hood/-ly, 語幹4字以上)で 語幹⇔派生 を相互リンク。
//       -sion/-al/-ous 等は短語の偶発一致(pen/pension, leg/legal)を生むため除外。
//   (4) 複合語：末尾が共通語(house/work/time…)で前半が見出し語なら相互リンク(greenhouse⇔green)。
// 関連語の意味は相手見出し語自身の意味を使う（正確）。手書きの family は保持し追記する。
// 巻き戻すには deriveFamilies 呼び出しを外して .map(normalize) に戻すだけ。
const FAM_PREFIX = new Set(['un', 'in', 'im', 'ir', 'il', 'dis', 'non', 're', 'over', 'under', 'mis', 'sub', 'pre', 'anti', 'up', 'out', 'de', 'ex', 'en', 'em', 'inter', 'trans', 'semi', 'co', 'com', 'con', 'a', 'ab', 'fore', 'counter'])
const FAM_STOP = new Set(['less', 'more'])
const FAM_SUFFIX = ['ness', 'less', 'ful', 'ship', 'hood', 'ly']
const FAM_TAIL = ['house', 'work', 'ware', 'time', 'way', 'place', 'land', 'light', 'room', 'book', 'side', 'yard', 'board', 'man', 'men', 'maker', 'keeper', 'mate', 'ground', 'line', 'field', 'fall', 'fold', 'print', 'storm', 'quake', 'craft', 'coast', 'mark', 'step']
const FAM_MAX = 6
const SAME_ORIGIN_RE = /([A-Za-z][A-Za-z'’-]{1,})(?:\s*[（(][^）)]*[）)])?\s*と同(?:語)?(?:源|系|根)/g
const deriveFamilies = (words) => {
  const head = new Map(words.map((w) => [w.word.toLowerCase(), w]))
  const links = new Map() // lowercased word -> Set(lowercased related headword)
  const add = (a, b) => {
    if (a === b || !head.has(b)) return
    if (!links.has(a)) links.set(a, new Set())
    links.get(a).add(b)
  }
  const pair = (a, b) => { add(a, b); add(b, a) }
  // (1) 語源が名指す基語（派生→基語）を抽出し双方向化
  for (const w of words) {
    const wl = w.word.toLowerCase()
    const note = w.etymology?.note || w.etymology?.origin || ''
    if (note) {
      let baseId = null
      for (const t of note.matchAll(/([A-Za-z][A-Za-z'’-]{2,})\(([^)]+)\)/g)) {
        const e = t[1].toLowerCase().replace(/[^a-z]/g, '')
        if (e.length < 4 || FAM_PREFIX.has(e) || FAM_STOP.has(e) || e === wl) continue
        const related = (wl.startsWith(e.slice(0, 4)) && wl.length > e.length) || wl.includes(e)
        if (related && head.has(e) && (!baseId || e.length > baseId.length)) baseId = e
      }
      if (baseId) pair(wl, baseId)

      // (2) 説明中で明示された同源語。全角/半角の意味括弧を許容する。
      for (const match of note.matchAll(SAME_ORIGIN_RE)) {
        const relatedId = match[1].toLowerCase().replace(/[^a-z]/g, '')
        if (head.has(relatedId)) pair(wl, relatedId)
      }
    }
    // 既存(手書き)の family が見出し語を指すなら双方向化
    for (const f of w.family) {
      const fw = f.w.toLowerCase()
      if (head.has(fw)) pair(wl, fw)
    }
  }
  // (3)(4) 形態リンク（超安全な接尾辞＋複合語）
  for (const b of head.keys()) {
    for (const suf of FAM_SUFFIX) {
      if (b.endsWith(suf) && b.length - suf.length >= 4) {
        const stem = b.slice(0, -suf.length)
        for (const a of [stem, stem + 'e', stem.replace(/i$/, 'y')]) {
          if (head.has(a)) { pair(a, b); break }
        }
      }
    }
    for (const t of FAM_TAIL) {
      if (b.endsWith(t) && b.length - t.length >= 3) {
        const a = b.slice(0, -t.length)
        if (head.has(a)) pair(a, b)
      }
    }
  }
  // 適用：手書き family を保持しつつ、関連見出し語を追記（重複除去・上限あり）
  for (const w of words) {
    const rel = links.get(w.word.toLowerCase())
    if (!rel || !rel.size) continue
    const have = new Set(w.family.map((f) => f.w.toLowerCase()))
    const extra = []
    for (const r of rel) {
      if (have.has(r)) continue
      const e = head.get(r)
      extra.push({ w: e.word, m: e.meanings.slice(0, 2).join('・') })
    }
    w.family = [...w.family, ...extra].slice(0, FAM_MAX)
  }
  return words
}

// 既存語と補完語は、語源カードIDを守るため別々に圧縮する。旧family索引だけは
// 境界を越えて双方向につなぐ必要があるため、圧縮後の内部データへ追加する。
// この自動追加分は辞書の「関連する語」には表示しない。
const applyCompletionFamilyBridges = (words) => {
  const byHead = new Map(words.map((word) => [word.word.toLowerCase(), word]))
  const byId = new Map(words.map((word) => [word.id, word]))
  const links = new Map()
  const add = (leftHead, rightHead) => {
    const left = byHead.get(leftHead.toLowerCase())
    const right = byHead.get(rightHead.toLowerCase())
    if (!left || !right || left.id === right.id) return
    const sourceGroup = (id) => completionIds.has(id)
      ? 'completion'
      : curriculum1900Ids.has(id)
        ? 'curriculum-1900'
        : 'legacy'
    if (sourceGroup(left.id) === sourceGroup(right.id)) return
    if (!links.has(left.id)) links.set(left.id, new Set())
    links.get(left.id).add(right.id)
  }
  const pair = (leftHead, rightHead) => {
    add(leftHead, rightHead)
    add(rightHead, leftHead)
  }

  for (const word of words) {
    const head = word.word.toLowerCase()
    const note = word.etymology?.note || word.etymology?.origin || ''
    let baseHead = null
    for (const match of note.matchAll(/([A-Za-z][A-Za-z'’-]{2,})\(([^)]+)\)/g)) {
      const candidate = match[1].toLowerCase().replace(/[^a-z]/g, '')
      if (
        candidate.length < 4 ||
        FAM_PREFIX.has(candidate) ||
        FAM_STOP.has(candidate) ||
        candidate === head
      ) continue
      const related =
        (head.startsWith(candidate.slice(0, 4)) && head.length > candidate.length) ||
        head.includes(candidate)
      if (
        related &&
        byHead.has(candidate) &&
        (!baseHead || candidate.length > baseHead.length)
      ) baseHead = candidate
    }
    if (baseHead) pair(head, baseHead)

    for (const match of note.matchAll(SAME_ORIGIN_RE)) {
      const relatedHead = match[1].toLowerCase().replace(/[^a-z]/g, '')
      if (byHead.has(relatedHead)) pair(head, relatedHead)
    }
    for (const family of word.family) {
      const relatedHead = family.w.toLowerCase()
      if (byHead.has(relatedHead)) pair(head, relatedHead)
    }
  }

  for (const head of byHead.keys()) {
    for (const suffix of FAM_SUFFIX) {
      if (!head.endsWith(suffix) || head.length - suffix.length < 4) continue
      const stem = head.slice(0, -suffix.length)
      for (const candidate of [stem, stem + 'e', stem.replace(/i$/, 'y')]) {
        if (byHead.has(candidate)) {
          pair(candidate, head)
          break
        }
      }
    }
    for (const tail of FAM_TAIL) {
      if (!head.endsWith(tail) || head.length - tail.length < 3) continue
      const candidate = head.slice(0, -tail.length)
      if (byHead.has(candidate)) pair(candidate, head)
    }
  }

  return words.map((word) => {
    const relatedIds = links.get(word.id)
    if (!relatedIds?.size) return word
    const currentIds = new Set(
      word.family
        .map((family) => byHead.get(family.w.toLowerCase())?.id)
        .filter(Boolean),
    )
    const additions = [...relatedIds]
      .filter((id) => !currentIds.has(id))
      .map((id) => {
        const related = byId.get(id)
        return { w: related.word, m: related.meanings.slice(0, 2).join('・') }
      })
    return additions.length
      ? { ...word, family: [...word.family, ...additions] }
      : word
  })
}

