export function histogramBins(values, width, start = 7) {
  const bins = []
  for (let from = start; from < 12 - 1e-9; from += width) {
    const to = from + width
    bins.push({ from: nice(from, 1), to: nice(to, 1), count: values.filter((value) => value >= from - 1e-9 && value < to - 1e-9).length })
  }
  return bins
}

export const median = (values) => {
  const sorted = [...values].sort((a, b) => a - b)
  const middle = Math.floor(sorted.length / 2)
  return sorted.length % 2 ? sorted[middle] : (sorted[middle - 1] + sorted[middle]) / 2
}

