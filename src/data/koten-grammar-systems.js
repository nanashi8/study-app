export const KOTEN_GRAMMAR_SYSTEM_BY_ID = Object.fromEntries(
  KOTEN_GRAMMAR_SYSTEMS.map((system) => [system.id, system]),
)

/** 体系表に出てくる文法項目の id（表の順・重なりなし）。 */
export function kotenGrammarSystemItemIds(system) {
  const ids = []
  for (const entry of system?.rows ?? []) {
    for (const id of entry.ids ?? []) if (!ids.includes(id)) ids.push(id)
  }
  return ids
}

/** その文法項目が出てくる体系表。 */
export const kotenGrammarSystemsFor = (itemId) =>
  KOTEN_GRAMMAR_SYSTEMS.filter((system) => system.rows.some((entry) => entry.ids?.includes(itemId)))
