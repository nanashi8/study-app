// ラテン語・ギリシャ語の接尾辞カード。
//
// 接頭辞カードで語の前半を、この接尾辞カードで語の後半を受け持つ。
// 接尾辞は意味よりも「品詞と働き」を決める部品で、production が名詞、
// productive が形容詞、productivity が性質の名詞…という語形変化の骨組みになる。
//
// 収録の条件（どちらかを満たし、かつ手で確かめた語だけを載せる）:
//  1) すでに語根カードに入っている＝ラテン語・ギリシャ語由来だと確認済みの語
//  2) 語源メモがその接尾辞を明示して分解している語（例:「accept ＋ -able」）
//
// 綴りが接尾辞に見えるだけで語幹の一部だった語（監査で除外）:
//   receive / perceive / conceive / deceive・survive / revive（-ive ではなく capere / vīvere）、
//   promise / premise / surmise・precise / concise・advise / advertise / revise / supervise
//   （-ize ではなく mittere / caedere / vidēre / vertere）、
//   assist / consist / insist / persist / resist / subsist（-ist ではなく sistere）、
//   secure / procure / endure / injure / conjure（-ure ではなく cūra / dūrāre / jūs / jūrāre）、
//   minor / senior（比較級の -ior）、behavior / outdoor（英語本来の語）、
