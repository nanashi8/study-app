function distinctDistractors(item, key, index) {
  const correct = item[key]
  const sameCategory = KOTEN_GRAMMAR.filter((candidate) => candidate.category === item.category)
  const ordered = [
    ...sameCategory.slice(index + 1),
    ...sameCategory.slice(0, index),
    ...KOTEN_GRAMMAR,
  ]
  const values = []
  for (const candidate of ordered) {
    const value = candidate[key]
    if (!value || value === correct || values.includes(value)) continue
    values.push(value)
    if (values.length === 3) break
  }
  return values
}

function rotateChoices(values, offset) {
  if (!values.length) return []
  const shift = offset % values.length
  return [...values.slice(shift), ...values.slice(0, shift)]
}

// 全項目に最低1問を保証する基礎問題。例文を手掛かりに、意味・接続・活用を
// 一問ずつ異なる角度で問うため、新項目を追加しても「覚えるだけ」で終わらない。
export const KOTEN_GRAMMAR_FOUNDATION_QUESTIONS = KOTEN_GRAMMAR.map((item, index) => {
  const keys = ['meaning', 'connection', 'forms']
  const key = keys[index % keys.length]
  const prompt = {
    meaning: `「${item.title}」の基本的な意味・働きとして最も適切なものを選びなさい。`,
    connection: `「${item.title}」の接続として最も適切なものを選びなさい。`,
    forms: `「${item.title}」の活用・形として最も適切なものを選びなさい。`,
  }[key]
  const choices = rotateChoices(
    [item[key], ...distinctDistractors(item, key, index)],
    index,
  )
  return {
    id: `kgq_foundation_${item.id}`,
    grammarIds: [item.id],
    category: item.category,
    level: index < 29 ? 'basic' : 'standard',
    format: key === 'meaning' ? 'meaning' : key === 'connection' ? 'connection' : 'inflection',
    style: 'foundation',
    source: '受験基礎型オリジナル',
    passage: item.example.ja,
    target: item.title,
    question: prompt,
    choices,
    answer: item[key],
    explanation: `${item.summary} 接続は「${item.connection}」。`,
    translation: item.example.gendai,
  }
})

export const KOTEN_GRAMMAR_QUESTIONS = [
  ...KOTEN_GRAMMAR_CONTEXT_QUESTIONS,
  ...KOTEN_GRAMMAR_FOUNDATION_QUESTIONS,
]

export const KOTEN_GRAMMAR_QUESTION_BY_ID = Object.fromEntries(
  KOTEN_GRAMMAR_QUESTIONS.map((item) => [item.id, item]),
)

export const getKotenGrammarQuestion = (id) => KOTEN_GRAMMAR_QUESTION_BY_ID[id]

export function kotenGrammarQuestionsFor(grammarIds) {
  const wanted = new Set((grammarIds ?? []).filter((id) => KOTEN_GRAMMAR_BY_ID[id]))
  if (!wanted.size) return KOTEN_GRAMMAR_QUESTIONS
  return KOTEN_GRAMMAR_QUESTIONS.filter((item) =>
    item.grammarIds.some((id) => wanted.has(id)),
  )
}

function shuffle(items, rng = Math.random) {
  const result = [...items]
  for (let index = result.length - 1; index > 0; index--) {
    const picked = Math.floor(rng() * (index + 1))
    ;[result[index], result[picked]] = [result[picked], result[index]]
  }
  return result
}

// 文脈問題を約3分の2、基礎問題を約3分の1にして、知識だけ・読解だけへ偏らせない。
export function pickKotenGrammarQuestions(
  grammarIds,
  { size = 12, rng = Math.random } = {},
) {
  const candidates = kotenGrammarQuestionsFor(grammarIds)
  const limit = Math.max(1, Math.min(Number(size) || 12, candidates.length))
  if (candidates.length <= limit) return shuffle(candidates, rng)

  const context = shuffle(candidates.filter((item) => item.style === 'context'), rng)
  const foundation = shuffle(candidates.filter((item) => item.style === 'foundation'), rng)
  const contextTarget = Math.min(context.length, Math.ceil(limit * (2 / 3)))
  const picked = [
    ...context.slice(0, contextTarget),
    ...foundation.slice(0, limit - contextTarget),
  ]
  if (picked.length < limit) {
    const used = new Set(picked.map((item) => item.id))
    picked.push(
      ...shuffle(candidates.filter((item) => !used.has(item.id)), rng)
        .slice(0, limit - picked.length),
    )
  }
  return shuffle(picked, rng)
}
