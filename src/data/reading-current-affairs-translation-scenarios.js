// 時事長文の英語順理解プラン。
// 各文字列は、解析器が確定したブロックを「 || 」、ブロック内の意味単位を
// 「／」で区切る。自然な和訳は passage.sentences[].ja に残し、ここでは
// 英文に現れる順番を崩さない対応訳だけを扱う。

import { CURRENT_AFFAIRS_PASSAGES } from './reading-current-affairs-passages.js'

const freeze = (value) => Object.freeze(value)
const englishWords = (text) =>
  (text.match(/[A-Za-z]+(?:['’][A-Za-z]+)*/g) || []).map((word) => word.toLowerCase())

// ブロック内の日本語意味単位に、英語側の対応範囲を明示する上書き。
const EN_SEGMENT_OVERRIDES = Object.freeze({})

function sentenceScenario(sentence, blockPlan, plan, passageId, sentenceIndex) {
  const blocks = blockPlan.split(' || ').map((item) => item.trim())
  const japaneseBlocks = plan.split(' || ').map((item) => item.trim())
  if (blocks.length !== japaneseBlocks.length) {
    throw new Error(
      '時事長文の語順プランでブロック数が一致しません: ' +
      passageId + '#' + (sentenceIndex + 1) + ' (' + blocks.length + ' / ' + japaneseBlocks.length + ')',
    )
  }
  if (JSON.stringify(blocks.flatMap(englishWords)) !== JSON.stringify(englishWords(sentence.en))) {
    throw new Error('時事長文の語順プランで原文を復元できません: ' + passageId + '#' + (sentenceIndex + 1))
  }

  return freeze(blocks.map((en, blockIndex) => {
    const jaSegments = freeze(
      japaneseBlocks[blockIndex].split('／').map((segment) => segment.trim()),
    )
    if (jaSegments.some((segment) => !segment)) {
      throw new Error('時事長文の語順プランに空の意味単位: ' + passageId + '#' + (sentenceIndex + 1))
    }
    const overrideKey = passageId + '#' + (sentenceIndex + 1) + '#' + (blockIndex + 1)
    const enSegments = EN_SEGMENT_OVERRIDES[overrideKey]
      ? freeze(EN_SEGMENT_OVERRIDES[overrideKey].split('／').map((segment) => segment.trim()))
      : null
    if (
      enSegments &&
      (
        enSegments.length !== jaSegments.length ||
        JSON.stringify(enSegments.flatMap(englishWords)) !== JSON.stringify(englishWords(en))
      )
    ) {
      throw new Error('時事長文の語順プランで英日の単位が一致しません: ' + overrideKey)
    }
    return freeze({
      en,
      ja: jaSegments.join(' → '),
      jaSegments,
      enSegments,
      reviewedSegments: true,
      speechJa: jaSegments.join('。次に、'),
      tip: '',
    })
  }))
}

function passageScenario(passage, blockPlans, plans) {
  if (passage.sentences.length !== plans.length || plans.length !== blockPlans.length) {
    throw new Error(
      '時事長文の語順プランで文数が一致しません: ' + passage.id +
      ' (' + passage.sentences.length + ' / ' + plans.length + ' / ' + blockPlans.length + ')',
    )
  }
  return freeze(plans.map((plan, index) =>
    sentenceScenario(passage.sentences[index], blockPlans[index], plan, passage.id, index)))
}

