// 事前確認した項目と実際の出題を一致させるため、予習画面へ進む時点で
// セッションの問題idを確定する。テストでは rng を固定できる。
export function pickKotenInterpretationIds(
  ids,
  { size = 12, rng = Math.random } = {},
) {
  const unique = [...new Set(ids ?? [])].filter((id) => getKotenInterpretation(id))
  for (let i = unique.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1))
    ;[unique[i], unique[j]] = [unique[j], unique[i]]
  }
  return size > 0 ? unique.slice(0, size) : unique
}
