const byTerm = new Map(GRAMMAR_REFERENCE_TERMS.map((entry) => [entry.term, entry]))
if (byTerm.size !== GRAMMAR_REFERENCE_TERMS.length) throw new Error('文法用語が重複しています')

export const grammarReferenceTerm = (term) => byTerm.get(term) ?? null
