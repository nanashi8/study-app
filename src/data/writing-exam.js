// 級別・文法別の入試型英作文。
//
// テーマ別英作文（writing.js）が「場面を決めて一段落を組み立てる」練習なのに対し、
// こちらは入試・英検で問われる「日本語の一文を、決まった文法の型で英語にする」練習に絞る。
// 1単元＝1つの文法項目で、英文法テスト（grammar.js）の topic と同じ名前をそろえ、
// 「型を読む → 英文をつくる → 誤りやすい点を確かめる」まで一続きにする。
//
// unit
//   topic  … 英文法テストと同じ単元名
//   form   … 英文の型（語順の公式）
//   focus  … この単元で確かめる判断（1文）
//   rule   … 型を使うときの決まり（2つ）
// question
//   ja     … 日本語の問題文
//   answer … 模範解答。語順カードの並べ替えにもそのまま使う
//   alt    … 自分で書くとき、正解として扱う別解
//   point  … その問題で確かめる文法の判断
//   trap   … 入試で減点されやすい誤り

const q = (id, ja, answer, point, trap, alt = []) => ({
  id,
  ja,
  answer,
  alt,
  point,
  trap,
})

const unit = (id, level, topic, title, form, focus, rule, questions) => ({
  id,
  level,
  topic,
  title,
  form,
  focus,
  rule,
  questions,
})

