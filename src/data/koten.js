// id を機械的に付与（'k001'…）。並びは RAW の順で安定。
export const KOTEN_WORDS = RAW.map((w, i) => ({
  id: `k${String(i + 1).padStart(3, '0')}`,
  ...w,
  meaning: w.meanings[0] ?? '',
}))

export const KOTEN_BY_ID = Object.fromEntries(KOTEN_WORDS.map((w) => [w.id, w]))

export const getKoten = (id) => KOTEN_BY_ID[id]

export const kotenByCategory = (catId) => KOTEN_WORDS.filter((w) => w.category === catId)

// カテゴリ（章）ビュー：画面はこれをそのまま描ける。空カテゴリは除く。
export const KOTEN_TOC = KOTEN_CATEGORIES.map((c) => ({
  category: c,
  words: kotenByCategory(c.id),
})).filter((t) => t.words.length > 0)

// クイズの誤答選択肢：まず同カテゴリの別語、足りなければ全体から補う。
export function pickKotenDistractors(word, count, rng = Math.random) {
  const same = kotenByCategory(word.category).filter((w) => w.id !== word.id)
  const others = KOTEN_WORDS.filter((w) => w.id !== word.id && w.category !== word.category)
  const pool = [...shuffle(same, rng), ...shuffle(others, rng)]
  const picked = []
  const usedMeaning = new Set([word.meaning])
  for (const w of pool) {
    if (picked.length >= count) break
    if (usedMeaning.has(w.meaning)) continue
    usedMeaning.add(w.meaning)
    picked.push(w)
  }
  return picked
}

function shuffle(arr, rng = Math.random) {
  const a = [...arr]
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}
