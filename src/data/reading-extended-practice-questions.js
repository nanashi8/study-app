const freezeList = (items) => Object.freeze(items.map((item) => Object.freeze(item)))

const orderQuestion = ({ id, sourceSentence, sourceJa, explain, readingRuleId, vocabIds }) => ({
  id,
  questionType: 'word-order',
  q: 'Arrange the words to rebuild the sentence from the passage.',
  questionJa: '本文の意味になるように、単語を英文の順に並べなさい。',
  cueJa: sourceJa,
  choices: Object.freeze([]),
  answer: sourceSentence,
  answerJa: sourceJa,
  sourceSentence,
  sourceJa,
  explain,
  readingRuleId,
  vocabIds: Object.freeze(vocabIds),
})

const choiceQuestion = ({
  id,
  questionType,
  q,
  questionJa,
  cueJa,
  answer,
  sourceSentence,
  sourceJa,
  explain,
  readingRuleId,
  vocabIds,
  choices,
}) => {
  const values = choices.map(([value]) => value)
  return {
    id,
    questionType,
    q,
    questionJa,
    cueJa,
    choices: Object.freeze(values),
    answer,
    answerJa: sourceJa,
    sourceSentence,
    sourceJa,
    explain,
    readingRuleId,
    vocabIds: Object.freeze(vocabIds),
    choiceTranslations: Object.freeze(Object.fromEntries(
      choices.map(([value, translation]) => [value, translation]),
    )),
    choiceNotes: Object.freeze(Object.fromEntries(
      choices.map(([value, , note]) => [value, note]),
    )),
  }
}

