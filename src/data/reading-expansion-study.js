const expression = (id, level, phrase, meaning, en, ja, note, kind = 'idiom') =>
  Object.freeze({
    id: 'rdx_' + id,
    kind,
    category: 'expression',
    level,
    phrase,
    meaning,
    meanings: [meaning],
    example: Object.freeze({ en, ja }),
    origin: note,
    note,
  })

const study = (expressions, phraseIds = []) => Object.freeze({
  phraseIds: Object.freeze(phraseIds),
  expressions: Object.freeze(expressions),
})

