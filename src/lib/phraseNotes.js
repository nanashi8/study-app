// 自動で作った熟語・構文カードの「成り立ち」と注意書きには、表現を問わず同じ文（表現の種類だけを言う説明や、
// 「例文で確認する」といった進め方の指示）が入っている。テストの答え合わせでは、その表現だけに当てはまる説明だけを出す。

const GENERIC_ORIGIN_PATTERNS = Object.freeze([
  /^前置詞を含む語のまとまり全体で一つの働きをする定型表現。$/,
  /^動詞と副詞・前置詞を一つの意味のまとまりとして捉える句動詞。$/,
  /^語を一つずつ直訳した意味から離れ、表現全体で慣用的な意味を作る。$/,
  /^語順と空所の位置を固定して、別の語を入れ替えて使える文の型。$/,
  /^英語で自然に結びつく語どうしを、語順を保った一まとまりとして覚える連語。$/,
  /^英語で自然に結びつく語どうしを、語順ごと一まとまりにした連語。$/,
  /^複数の語を切り離さず、一つの意味として使う定型表現。$/,
  /^前置詞が持つ位置・方向・関係の感覚を含め、まとまり全体で一つの働きをする表現。\s*先頭の .+ も意味の一部。$/,
  /^動詞に副詞・前置詞の方向感覚が加わり、表現全体で一つの動作を表す句動詞。\s*この表現では .+ と .+ を切り離さず捉える。$/,
  /^文と文の論理関係や、話の流れを読み手に示す談話表現。$/,
  /^文と文の関係や話の流れを明示する談話表現。$/,
  /^会話の場面と語順を一つのかたまりとして再利用する定型表現。$/,
  /^会話で繰り返し使う語順を、そのまま再利用できる定型表現。$/,
  /^単語を直訳しただけでは出にくい意味を、表現全体で捉える慣用句。$/,
])

const GENERIC_NOTE_PATTERNS = Object.freeze([
  /^直訳のイメージと実際の意味を結び付け、まとまりのまま覚える。$/,
  /^.+の役割と、後ろに原形・動名詞・節のどれが来るかを確認する。$/,
  /^前置詞まで含めて覚え、後ろに続く名詞や動名詞を確認する。$/,
  /^目的語を置く位置と、自動詞・他動詞の違いまで例文で確認する。$/,
  /^逆接・追加・理由・言い換えなど、前後の関係とセットで使う。$/,
  /^場面、相手との距離、丁寧さを例文と一緒に覚える。$/,
  /^日本語から一語ずつ直訳せず、この語の組み合わせで使う。$/,
])

const matchesAny = (patterns, text) => {
  const value = String(text ?? '').replace(/\s+/g, ' ').trim()
  return Boolean(value) && patterns.some((pattern) => pattern.test(value))
}

/** 表現の種類だけを言う「成り立ち」か（その表現の成り立ちを説明していない）。 */
export const isGenericPhraseOrigin = (text) => matchesAny(GENERIC_ORIGIN_PATTERNS, text)

/** どの表現にも当てはまる進め方の指示だけの注意書きか。 */
export const isGenericPhraseNote = (text) => matchesAny(GENERIC_NOTE_PATTERNS, text)
