const ENTRIES = KANBUN_FURIGANA_ENTRIES
  .map(([text, reading, okurigana = '']) => ({ text, reading, okurigana }))
  .sort((left, right) => (
    (right.text.length + right.okurigana.length) - (left.text.length + left.okurigana.length)
  ))

const KANJI = /[一-鿿々]/

export const isKanbunKanji = (character) => KANJI.test(character)

function entriesWith(extraReadings = []) {
  if (!Array.isArray(extraReadings) || !extraReadings.length) return ENTRIES
  const extra = extraReadings
    .map((entry) => (Array.isArray(entry)
      ? { text: entry[0], reading: entry[1], okurigana: entry[2] ?? '' }
      : entry))
    .filter((entry) => entry?.text && entry?.reading && entry.text !== entry.reading)
  return [...extra, ...ENTRIES].sort((left, right) => (
    (right.text.length + (right.okurigana?.length ?? 0))
      - (left.text.length + (left.okurigana?.length ?? 0))
  ))
}

// 文字列を「ルビを振る部分」と「そのままの部分」へ切り分ける。
// 送り仮名は一致条件にだけ使い、ルビは漢字の上にだけ乗せる。
export function tokenizeKanbunText(value, extraReadings = []) {
  const text = value == null ? '' : String(value)
  if (!text) return []

  const entries = entriesWith(extraReadings)
  const segments = []
  let cursor = 0
  let plainStart = 0

  while (cursor < text.length) {
    const match = entries.find((entry) => (
      text.startsWith(entry.text + (entry.okurigana ?? ''), cursor)
    ))
    if (!match) {
      cursor += 1
      continue
    }
    if (cursor > plainStart) segments.push({ text: text.slice(plainStart, cursor) })
    segments.push({ text: match.text, reading: match.reading })
    cursor += match.text.length
    plainStart = cursor
  }

  if (plainStart < text.length) segments.push({ text: text.slice(plainStart) })
  return segments
}

// ふりがなの付いていない漢字を返す。監査で「振り漏れ0」を確かめるために使う。
export function uncoveredKanbunKanji(value, extraReadings = []) {
  const missing = []
  for (const segment of tokenizeKanbunText(value, extraReadings)) {
    if (segment.reading) continue
    for (const character of segment.text) {
      if (KANJI.test(character)) missing.push(character)
    }
  }
  return missing
}

export function kanbunTextForSearch(value) {
  const text = value == null ? '' : String(value)
  const reading = tokenizeKanbunText(text)
    .map((segment) => segment.reading ?? segment.text)
    .join('')
  return `${text} ${reading}`
}
