const DEFAULT_ENTRIES = KOTEN_FURIGANA_ENTRIES
  .map(([text, reading]) => ({ text, reading }))
  .sort((left, right) => right.text.length - left.text.length)

function normalizeExtraReadings(readings) {
  if (!Array.isArray(readings)) return []
  return readings
    .map((entry) => {
      if (Array.isArray(entry)) return { text: entry[0], reading: entry[1] }
      return entry
    })
    .filter((entry) => entry?.text && entry?.reading && entry.text !== entry.reading)
}

function readingEntries(extraReadings) {
  const entries = new Map(DEFAULT_ENTRIES.map((entry) => [entry.text, entry.reading]))
  for (const entry of normalizeExtraReadings(extraReadings)) {
    entries.set(String(entry.text), String(entry.reading))
  }
  return [...entries]
    .map(([text, reading]) => ({ text, reading }))
    .sort((left, right) => right.text.length - left.text.length)
}

export function tokenizeKotenText(value, extraReadings = []) {
  const text = value == null ? '' : String(value)
  if (!text) return []

  const entries = extraReadings.length ? readingEntries(extraReadings) : DEFAULT_ENTRIES
  const segments = []
  let cursor = 0
  let plainStart = 0

  while (cursor < text.length) {
    const match = entries.find((entry) => text.startsWith(entry.text, cursor))
    if (!match) {
      cursor += 1
      continue
    }

    if (cursor > plainStart) {
      segments.push({ text: text.slice(plainStart, cursor) })
    }
    segments.push({ text: match.text, reading: match.reading })
    cursor += match.text.length
    plainStart = cursor
  }

  if (plainStart < text.length) {
    segments.push({ text: text.slice(plainStart) })
  }
  return segments
}

export function kotenTextForSearch(value) {
  const text = value == null ? '' : String(value)
  const reading = tokenizeKotenText(text)
    .map((segment) => segment.reading ?? segment.text)
    .join('')
  return `${text} ${reading}`
}
